'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');

/**
 * Input validation shared by restore, quick actions, the tab bridge and IPC.
 *
 * Everything that ends up launching a process or opening a URL passes through
 * here first. That data comes from browser tabs, window titles and files on
 * disk, so none of it is trusted — a URL or path is only ever used after it
 * has been parsed and normalized below.
 */

const MAX_URL_LENGTH = 8192;
const MAX_PATH_LENGTH = 1024;

/**
 * Return a normalized web URL, or null if the input isn't one.
 * http/https only; with allowFile, also file:// URLs that point at a local
 * disk (a host or a leading // in a file URL means a network share).
 */
function sanitizeWebUrl(input, { allowFile = false } = {}) {
  if (typeof input !== 'string' || !input || input.length > MAX_URL_LENGTH) return null;
  let u;
  try { u = new URL(input.trim()); } catch (_) { return null; }
  if (u.protocol === 'http:' || u.protocol === 'https:') {
    return u.hostname ? u.href : null;
  }
  if (allowFile && u.protocol === 'file:' && !u.host && !u.pathname.startsWith('//')) {
    return u.href;
  }
  return null;
}

/** \\server\share, \\?\..., \\.\..., //server — anything that isn't a plain local path. */
function isUncOrDevicePath(p) {
  return /^[\\/]{2}/.test(p);
}

/**
 * A plain absolute path on a local drive (C:\... on Windows), or null.
 * Used for executables and for the storage folder.
 */
function localAbsolutePath(p) {
  if (typeof p !== 'string' || !p || p.length > MAX_PATH_LENGTH || p.includes('\0')) return null;
  if (isUncOrDevicePath(p)) return null;
  const n = path.normalize(p);
  if (!path.isAbsolute(n) || isUncOrDevicePath(n)) return null;
  if (os.platform() === 'win32') {
    if (!/^[a-zA-Z]:\\/.test(n)) return null;
    if (n.slice(2).includes(':')) return null; // alternate data streams (file.exe:stream)
  }
  return n;
}

/**
 * Validate a program to launch. Returns the normalized path, or null.
 * On Windows only the listed extensions are accepted (default: .exe).
 */
function validateExecutablePath(p, { extensions = ['.exe'] } = {}) {
  const n = localAbsolutePath(p);
  if (!n) return null;
  if (os.platform() === 'win32' && !extensions.includes(path.extname(n).toLowerCase())) return null;
  try {
    if (!fs.statSync(n).isFile()) return null;
  } catch (_) {
    return null;
  }
  return n;
}

/** Store ids are generated by store.uid(): "<prefix>_<12 hex>". */
function isId(v) {
  return typeof v === 'string' && /^[a-z]{2,4}_[0-9a-f]{12}$/.test(v);
}

/** Electron accelerator / chord text as produced by the hotkey recorder. Empty = none. */
function isHotkey(v) {
  return typeof v === 'string' && /^[\x20-\x7E]{0,64}$/.test(v);
}

/** Trimmed, length-capped string; '' for anything that isn't a string. */
function cleanText(v, max) {
  return typeof v === 'string' ? v.trim().slice(0, max) : '';
}

module.exports = {
  sanitizeWebUrl,
  isUncOrDevicePath,
  localAbsolutePath,
  validateExecutablePath,
  isId,
  isHotkey,
  cleanText,
};
